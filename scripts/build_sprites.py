#!/usr/bin/env python3
"""Packs the play animations' pixel art into components/gameday/sprites.h.

The art lives as ASCII in firmware/art/sprites/*.txt:

    @legend .osdJTHPKbwBGMxy      one character per palette slot, slot 0 first
    @frame qb.set 16x24 anchor 7,23
    <one row of characters per pixel row>

A frame's name is "<set>.<pose>"; frames of a set keep their file order. The
anchor is the point placed on the ground, on a row that holds a foot pixel
(slot 8). Pixels pack at 4 bits, two a byte, high nibble first.

    python3 scripts/build_sprites.py            write the header
    python3 scripts/build_sprites.py --check    fail when the header is stale
    python3 scripts/build_sprites.py --selftest round-trip a frame
"""

import glob
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, "firmware", "art", "sprites")
OUT = os.path.join(ROOT, "components", "gameday", "sprites.h")
FOOT_SLOT = 8


def parse(text, name="art"):
    legend = None
    frames = []
    cur = None
    for n, line in enumerate(text.splitlines(), 1):
        line = line.rstrip()
        where = f"{name}:{n}"
        if line.startswith("#"):
            continue
        if line.startswith("@legend "):
            legend = line.split(None, 1)[1]
            if len(legend) != 16 or len(set(legend)) != 16:
                raise SystemExit(f"{where}: the legend needs 16 distinct characters")
            continue
        if line.startswith("@frame "):
            parts = line.split()
            if len(parts) != 5 or parts[3] != "anchor" or "." not in parts[1]:
                raise SystemExit(f"{where}: expected '@frame set.pose WxH anchor x,y'")
            w, h = (int(v) for v in parts[2].split("x"))
            ax, ay = (int(v) for v in parts[4].split(","))
            cur = {"set": parts[1].split(".")[0], "pose": parts[1].split(".", 1)[1], "w": w, "h": h,
                   "ax": ax, "ay": ay, "rows": [], "where": where}
            frames.append(cur)
            continue
        if not line:
            cur = None
            continue
        if cur is None:
            raise SystemExit(f"{where}: pixels outside a frame")
        if legend is None:
            raise SystemExit(f"{where}: pixels before the legend")
        cur["rows"].append([legend.index(c) if c in legend else -1 for c in line])
        if -1 in cur["rows"][-1]:
            raise SystemExit(f"{where}: a character not in the legend")
    for f in frames:
        if len(f["rows"]) != f["h"] or any(len(r) != f["w"] for r in f["rows"]):
            raise SystemExit(f"{f['where']}: the pixels aren't {f['w']}x{f['h']}")
        if f["w"] > 255 or f["h"] > 255 or not (0 <= f["ax"] < f["w"] and 0 <= f["ay"] < f["h"]):
            raise SystemExit(f"{f['where']}: the anchor is outside the frame")
        if FOOT_SLOT not in f["rows"][f["ay"]]:
            raise SystemExit(f"{f['where']}: the anchor's row has no foot pixel")
    return frames


def pack(f):
    flat = [v for r in f["rows"] for v in r]
    if len(flat) % 2:
        flat.append(0)
    return bytes((flat[i] << 4) | flat[i + 1] for i in range(0, len(flat), 2))


def unpack(data, w, h):
    flat = []
    for b in data:
        flat += [b >> 4, b & 15]
    return [flat[y * w:(y + 1) * w] for y in range(h)]


def ident(s):
    return "".join(p.capitalize() for p in s.replace("-", "_").split("_"))


def header(frames):
    out = ["// Generated by scripts/build_sprites.py; do not edit",
           "// Source: firmware/art/sprites/*.txt",
           "#pragma once", "", "#include <cstdint>", "", "namespace espn {", "",
           "struct Sprite {", "  uint8_t w, h, ax, ay;", "  const uint8_t *px;  // 4 bpp, high nibble first", "};", ""]
    sets = []
    for f in frames:
        if f["set"] not in sets:
            sets.append(f["set"])
    for s in sets:
        mine = [f for f in frames if f["set"] == s]
        for i, f in enumerate(mine):
            data = pack(f)
            body = ", ".join(f"0x{b:02X}" for b in data)
            out.append(f"inline constexpr uint8_t kSpr{ident(s)}{i}[] = {{{body}}};")
        out.append(f"inline constexpr Sprite kSpr{ident(s)}[] = {{")
        for i, f in enumerate(mine):
            out.append(f"    {{{f['w']}, {f['h']}, {f['ax']}, {f['ay']}, kSpr{ident(s)}{i}}},  // {f['pose']}")
        out.append("};")
        names = ", ".join(f"SPR_{s.upper()}_{f['pose'].upper()}" for f in mine)
        out.append(f"enum : uint8_t {{ {names} }};")
        out.append("")
    out.append("}  // namespace espn")
    out.append("")
    return "\n".join(out)


def build():
    frames = []
    for path in sorted(glob.glob(os.path.join(ART, "*.txt"))):
        with open(path, encoding="utf-8") as fh:
            frames += parse(fh.read(), os.path.relpath(path, ROOT))
    return header(frames)


def selftest():
    art = "@legend .osdJTHPKbwBGMxy\n@frame t.a 3x2 anchor 1,1\n.J.\nKbK\n"
    f = parse(art)[0]
    assert unpack(pack(f), 3, 2) == f["rows"], "round trip"
    assert pack(f) == bytes([0x04, 0x08, 0x98]), pack(f)
    for bad in ("@legend .osdJTHPKbwBGMxy\n@frame t.a 3x2 anchor 1,0\n.J.\nKbK\n",
                "@legend .osdJTHPKbwBGMxy\n@frame t.a 3x2 anchor 1,1\n.J.\nKb\n",
                "@legend .osdJTHPKbwBGMxy\n@frame t.a 3x2 anchor 1,1\n.Z.\nKbK\n"):
        try:
            parse(bad)
        except SystemExit:
            continue
        raise AssertionError("accepted bad art")
    build()
    print("build_sprites selftest: ok")


def main():
    if "--selftest" in sys.argv:
        selftest()
        return 0
    text = build()
    if "--check" in sys.argv:
        try:
            with open(OUT, encoding="utf-8") as fh:
                same = fh.read() == text
        except FileNotFoundError:
            same = False
        if not same:
            print("components/gameday/sprites.h is stale: run python3 scripts/build_sprites.py", file=sys.stderr)
            return 1
        print("sprites.h is current")
        return 0
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
